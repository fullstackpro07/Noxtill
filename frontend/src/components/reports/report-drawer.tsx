import { ApiError } from "@/lib/api-client";
import {
  downloadRun,
  fetchRunAudit,
  fetchRunDetail,
  generateReport,
  type RunDetail,
  type RunSummary,
} from "@/lib/reports-api";
import { REPORT_KIND_LABELS } from "@/lib/reports";
import { BulletList, NoteBox, PanelRows, R, RIcon, ageLabel, chipStyle, relativeDateTime, validationIcon, validationLabel, validationTone, type Tone } from "./reports-ui";
